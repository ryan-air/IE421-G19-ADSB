#!/usr/bin/env python3
"""Generate feed message definitions for C++, JavaScript, and Python.

One schema (protocol/schema/feed_v0.json) is the source of truth for the wire
format. This script validates it and writes:

  core/include/adsb/protocol/feed_messages.hpp   C++20 structs + read/write
  protocol/generated/feed_messages.mjs           JavaScript (DataView), ES module
  protocol/generated/feed_messages.py            Python (struct, optional NumPy)
  protocol/golden/packet_v0.bin                  golden datagram for all tests
  protocol/golden/packet_v0.json                 its decoded contents

Usage:
  python3 protocol/gen.py           regenerate everything
  python3 protocol/gen.py --check   exit 1 if any generated file is stale (CI)

Only the standard library is used.
"""

from __future__ import annotations

import argparse
import json
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = ROOT / "protocol" / "schema" / "feed_v0.json"
OUT_CPP = ROOT / "core" / "include" / "adsb" / "protocol" / "feed_messages.hpp"
OUT_JS = ROOT / "protocol" / "generated" / "feed_messages.mjs"
OUT_PY = ROOT / "protocol" / "generated" / "feed_messages.py"
OUT_GOLDEN_BIN = ROOT / "protocol" / "golden" / "packet_v0.bin"
OUT_GOLDEN_JSON = ROOT / "protocol" / "golden" / "packet_v0.json"

# type -> (size, struct char, C++ type, signed, JS DataView suffix, numpy)
SCALARS = {
    "u8": (1, "B", "std::uint8_t", False, "Uint8", "u1"),
    "i8": (1, "b", "std::int8_t", True, "Int8", "i1"),
    "u16": (2, "H", "std::uint16_t", False, "Uint16", "<u2"),
    "i16": (2, "h", "std::int16_t", True, "Int16", "<i2"),
    "u32": (4, "I", "std::uint32_t", False, "Uint32", "<u4"),
    "i32": (4, "i", "std::int32_t", True, "Int32", "<i4"),
    "u64": (8, "Q", "std::uint64_t", False, "BigUint64", "<u8"),
    "i64": (8, "q", "std::int64_t", True, "BigInt64", "<i8"),
}
CHAR_RE = re.compile(r"^char\[(\d+)\]$")
HEADER = "GENERATED by protocol/gen.py from protocol/schema/feed_v0.json. DO NOT EDIT."


class SchemaError(Exception):
    pass


# ---------------------------------------------------------------------------
# Schema loading and validation
# ---------------------------------------------------------------------------

def field_size(ftype: str) -> int:
    if ftype in SCALARS:
        return SCALARS[ftype][0]
    m = CHAR_RE.match(ftype)
    if m:
        return int(m.group(1))
    raise SchemaError(f"unknown field type {ftype!r}")


def field_align(ftype: str) -> int:
    return SCALARS[ftype][0] if ftype in SCALARS else 1


def range_of(ftype: str) -> tuple[int, int]:
    size, _, _, signed, _, _ = SCALARS[ftype]
    bits = 8 * size
    return (-(1 << (bits - 1)), (1 << (bits - 1)) - 1) if signed else (0, (1 << bits) - 1)


CPP_KEYWORDS = {
    "alignas", "alignof", "and", "auto", "bool", "break", "case", "catch", "char", "class", "const",
    "continue", "default", "delete", "do", "double", "else", "enum", "explicit", "export", "extern",
    "false", "float", "for", "friend", "goto", "if", "inline", "int", "long", "namespace", "new",
    "not", "operator", "or", "private", "protected", "public", "register", "return", "short",
    "signed", "sizeof", "static", "struct", "switch", "template", "this", "throw", "true", "try",
    "typedef", "typename", "union", "unsigned", "using", "virtual", "void", "volatile", "while",
}
IDENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def load_schema() -> dict:
    schema = json.loads(SCHEMA.read_text())
    seen_types = set()
    seen_structs = set()
    for b in schema["bitsets"]:
        width = 8 * SCALARS[b["type"]][0]
        for bit in b["bits"]:
            # < 31 also keeps JavaScript's 32-bit shifts positive.
            if not 0 <= bit["bit"] < min(width, 31):
                raise SchemaError(f"{b['name']}.{bit['name']}: bit {bit['bit']} does not fit {b['type']}")
    for s in schema["structs"]:
        if s["name"] in seen_structs or not IDENT_RE.match(s["name"]):
            raise SchemaError(f"bad or duplicate struct name {s['name']!r}")
        seen_structs.add(s["name"])
        if "example" not in s:
            raise SchemaError(f"{s['name']}: missing example (used by the golden tests)")
        offset = 0
        names = set()
        for f in s["fields"]:
            if f["name"] in names:
                raise SchemaError(f"{s['name']}: duplicate field {f['name']}")
            if not IDENT_RE.match(f["name"]) or f["name"] in CPP_KEYWORDS:
                raise SchemaError(f"{s['name']}.{f['name']}: not a usable identifier")
            if "null" in f and f["type"] not in SCALARS:
                raise SchemaError(f"{s['name']}.{f['name']}: null values are only for integer fields")
            if "pad" in f and (not CHAR_RE.match(f["type"]) or len(f["pad"]) != 1):
                raise SchemaError(f"{s['name']}.{f['name']}: pad must be one character on a char[N] field")
            names.add(f["name"])
            size = field_size(f["type"])
            if not s.get("packed") and offset % field_align(f["type"]) != 0:
                raise SchemaError(
                    f"{s['name']}.{f['name']}: offset {offset} not aligned to "
                    f"{field_align(f['type'])}; reorder fields or mark the struct packed")
            f["offset"] = offset
            f["size"] = size
            offset += size
            if "null" in f:
                lo, hi = range_of(f["type"])
                if not lo <= f["null"] <= hi:
                    raise SchemaError(f"{s['name']}.{f['name']}: null out of range")
        s["wire_size"] = offset
        if not s.get("packed"):
            biggest = max(field_align(f["type"]) for f in s["fields"])
            if offset % biggest != 0:
                raise SchemaError(f"{s['name']}: size {offset} leaves tail padding")
        if "type_char" in s:
            tc = s["type_char"]
            if len(tc) != 1 or tc in seen_types:
                raise SchemaError(f"{s['name']}: bad or duplicate type_char {tc!r}")
            seen_types.add(tc)
            first = s["fields"][0]
            if first["name"] != "msg_type" or first["type"] != "u8":
                raise SchemaError(f"{s['name']}: first field must be u8 msg_type")
            if s["example"]["msg_type"] != ord(tc):
                raise SchemaError(f"{s['name']}: example msg_type must be ord({tc!r})")
        ex = s["example"]
        missing = names - set(ex)
        if missing:
            raise SchemaError(f"{s['name']}: example missing {sorted(missing)}")
        for f in s["fields"]:
            v = ex[f["name"]]
            if f["type"] in SCALARS:
                lo, hi = range_of(f["type"])
                if not isinstance(v, int) or not lo <= v <= hi:
                    raise SchemaError(f"{s['name']}.{f['name']}: example {v!r} out of range for {f['type']}")
            elif not isinstance(v, str) or len(v.encode("latin-1")) > f["size"]:
                raise SchemaError(f"{s['name']}.{f['name']}: example must be a string of <= {f['size']} bytes")
    return schema


def camel(name: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in name.split("_"))


def snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def struct_format(s: dict) -> str:
    parts = []
    for f in s["fields"]:
        m = CHAR_RE.match(f["type"])
        parts.append(f"{m.group(1)}s" if m else SCALARS[f["type"]][1])
    return "<" + "".join(parts)


