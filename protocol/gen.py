def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = ap.parse_args()
    try:
        schema = load_schema()
        golden_bin, golden_json = gen_golden(schema)
    except SchemaError as e:
        print(f"schema error: {e}", file=sys.stderr)
        return 2

    outputs = {
        OUT_CPP: gen_cpp(schema).encode(),
        OUT_JS: gen_js(schema).encode(),
        OUT_PY: gen_py(schema).encode(),
        OUT_GOLDEN_BIN: golden_bin,
        OUT_GOLDEN_JSON: golden_json.encode(),
    }
    stale = []
    for path, data in outputs.items():
        current = path.read_bytes() if path.exists() else None
        if current == data:
            continue
        if args.check:
            stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("stale generated files (run python3 protocol/gen.py):", file=sys.stderr)
        for p in stale:
            print(f"  {p}", file=sys.stderr)
        return 1
    if args.check:
        print("generated files are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
