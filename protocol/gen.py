def gen_js(schema: dict) -> str:
    o = []
    w = o.append
    w(f"// {HEADER}")
    w(f"// {schema['doc']}")
    w("// 64-bit fields are BigInt; char[N] fields are strings.")
    w("")
    for c in schema["constants"]:
        w(f"export const {c['name']} = {c['value']};  // {c['doc']}")
    w("")
    for b in schema["bitsets"]:
        w(f"// {b['doc']}")
        w(f"export const {b['name']} = Object.freeze({{")
        for bit in b["bits"]:
            w(f"  {bit['name']}: {1 << bit['bit']},  // {bit['doc']}")
        w("});")
        w("")
    w("const decodeChars = (view, off, n) => {")
    w("  let s = '';")
    w("  for (let i = 0; i < n; i++) s += String.fromCharCode(view.getUint8(off + i));")
    w("  return s;")
    w("};")
    w("const encodeChars = (view, off, n, str, pad = 0) => {")
    w("  for (let i = 0; i < n; i++) view.setUint8(off + i, i < str.length ? str.charCodeAt(i) & 0xff : pad);")
    w("};")
    w("")
    for s in schema["structs"]:
        name = s["name"]
        w(f"// {s['doc']}")
        w(f"export const {name}Size = {s['wire_size']};")
        nulls = {f["name"]: f["null"] for f in s["fields"] if "null" in f}
        if nulls:
            body = ", ".join(f"{k}: {v}" for k, v in nulls.items())
            w(f"// Values meaning 'unknown' for {name} fields.")
            w(f"export const {name}Null = Object.freeze({{ {body} }});")
        if "type_char" in s:
            w(f"export const {name}Type = '{s['type_char']}';")
        w(f"export function decode{name}(view, offset = 0) {{")
        w("  return {")
        for f in s["fields"]:
            m = CHAR_RE.match(f["type"])
            if m:
                w(f"    {f['name']}: decodeChars(view, offset + {f['offset']}, {m.group(1)}),")
            else:
                le = ", true" if f["size"] > 1 else ""
                w(f"    {f['name']}: view.get{SCALARS[f['type']][4]}(offset + {f['offset']}{le}),")
        w("  };")
        w("}")
        w(f"export function encode{name}(msg, view, offset = 0) {{")
        for f in s["fields"]:
            m = CHAR_RE.match(f["type"])
            if m:
                pad = ord(f["pad"]) if "pad" in f else 0
                w(f"  encodeChars(view, offset + {f['offset']}, {m.group(1)}, msg.{f['name']}, {pad});")
            else:
                le = ", true" if f["size"] > 1 else ""
                val = f"BigInt(msg.{f['name']})" if f["size"] == 8 else f"msg.{f['name']}"
                w(f"  view.set{SCALARS[f['type']][4]}(offset + {f['offset']}, {val}{le});")
        w("}")
        w("")
    typed = [s for s in schema["structs"] if "type_char" in s]
    w("const decoders = {")
    for s in typed:
        w(f"  '{s['type_char']}': [decode{s['name']}, {s['wire_size']}, '{s['name']}'],")
    w("};")
    w("")
    w("// Decodes one datagram. Returns {header, messages: [{seq, type, name, msg}]}.")
    w("// Unknown message types are returned with msg = null (forward compatibility).")
    w("export function decodePacket(buffer) {")
    w("  const view = buffer instanceof DataView ? buffer : new DataView(buffer.buffer ?? buffer, buffer.byteOffset ?? 0, buffer.byteLength);")
    w("  if (view.byteLength < PacketHeaderSize) throw new RangeError('packet shorter than header');")
    w("  const header = decodePacketHeader(view, 0);")
    w("  const messages = [];")
    w("  if (header.count === kEndOfSessionCount || header.count === kHeartbeatCount) {")
    w("    if (view.byteLength !== PacketHeaderSize) throw new RangeError('heartbeat / end-of-session packet has a body');")
    w("    return { header, messages };")
    w("  }")
    w("  let off = PacketHeaderSize;")
    w("  for (let i = 0; i < header.count; i++) {")
    w("    if (off + 2 > view.byteLength) throw new RangeError('truncated message length');")
    w("    const len = view.getUint16(off, true);")
    w("    off += 2;")
    w("    if (off + len > view.byteLength) throw new RangeError('truncated message body');")
    w("    const type = len > 0 ? String.fromCharCode(view.getUint8(off)) : '';")
    w("    const d = decoders[type];")
    w("    const msg = d && len >= d[1] ? d[0](view, off) : null;")
    w("    messages.push({ seq: header.seq + BigInt(i), type, name: d ? d[2] : null, msg });")
    w("    off += len;")
    w("  }")
    w("  if (off !== view.byteLength) throw new RangeError('trailing bytes after the last message');")
    w("  return { header, messages };")
    w("}")
    w("")
    return "\n".join(o)


