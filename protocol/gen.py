def gen_golden(schema: dict) -> tuple[bytes, str]:
    by_name = {s["name"]: s for s in schema["structs"]}

    def pack(s: dict) -> bytes:
        vals = []
        for f in s["fields"]:
            v = s["example"][f["name"]]
            m = CHAR_RE.match(f["type"])
            vals.append(v.encode("latin-1").ljust(int(m.group(1)), b"\0") if m else v)
        return struct.pack(struct_format(s), *vals)

    g = schema["golden_packet"]
    header = by_name[g["header"]]
    if header["example"]["count"] != len(g["messages"]):
        raise SchemaError("golden header count must equal number of golden messages")
    body = b""
    for name in g["messages"]:
        m = pack(by_name[name])
        body += struct.pack("<H", len(m)) + m
    data = pack(header) + body
    if len(data) > next(c["value"] for c in schema["constants"] if c["name"] == "kMaxUdpPayload"):
        raise SchemaError("golden packet exceeds kMaxUdpPayload")
    def json_fields(st: dict) -> dict:
        # 64-bit integers are written as strings: JSON numbers lose precision
        # above 2^53 in JavaScript (and many other parsers).
        return {f["name"]: (str(st["example"][f["name"]]) if f.get("size") == 8 else st["example"][f["name"]])
                for f in st["fields"]}

    decoded = {
        "note": "64-bit integer fields are strings to avoid JSON precision loss",
        "header": json_fields(header),
        "messages": [{"name": n, "fields": json_fields(by_name[n])} for n in g["messages"]],
        "size": len(data),
    }
    return data, json.dumps(decoded, indent=2, sort_keys=False) + "\n"


