# C++
# ---------------------------------------------------------------------------

def cpp_type(f: dict) -> str:
    m = CHAR_RE.match(f["type"])
    return f"std::array<char, {m.group(1)}>" if m else SCALARS[f["type"]][2]


def cpp_literal(value: int, ftype: str) -> str:
    lo, _ = range_of(ftype)
    if value == lo and lo < 0:
        # INT_MIN cannot be written as a negative literal without overflow.
        return f"std::numeric_limits<{SCALARS[ftype][2]}>::min()"
    suffix = "" if SCALARS[ftype][3] else "u"
    if SCALARS[ftype][0] == 8:
        suffix += "ll"
    return f"{value}{suffix}"


def gen_cpp(schema: dict) -> str:
    o = []
    w = o.append
    w(f"// {HEADER}")
    w("//")
    w(f"// {schema['doc']}")
    w(f"// Schema version {schema['version']} ({schema['status']}).")
    w("")
    w("#pragma once")
    w("")
    w("#include <array>")
    w("#include <bit>")
    w("#include <cstddef>")
    w("#include <cstdint>")
    w("#include <cstring>")
    w("#include <limits>")
    w("")
    w("namespace adsb::protocol {")
    w("")
    w("static_assert(std::endian::native == std::endian::little,")
    w("              \"the feed is little-endian; big-endian hosts need byte swapping\");")
    w("")
    for c in schema["constants"]:
        w(f"// {c['doc']}")
        w(f"inline constexpr {SCALARS[c['type']][2]} {c['name']} = {c['value']};")
    w("")
    for b in schema["bitsets"]:
        ns = snake(b["name"])
        w(f"// {b['doc']}")
        w(f"namespace {ns} {{")
        for bit in b["bits"]:
            w(f"inline constexpr {SCALARS[b['type']][2]} {bit['name']} = "
              f"static_cast<{SCALARS[b['type']][2]}>(1u << {bit['bit']});  // {bit['doc']}")
        w(f"}}  // namespace {ns}")
        w("")

    for s in schema["structs"]:
        w(f"// {s['doc']}")
        w(f"struct {s['name']} {{")
        if "type_char" in s:
            w(f"  static constexpr char kTypeChar = '{s['type_char']}';")
        w(f"  static constexpr std::size_t kWireSize = {s['wire_size']};")
        for f in s["fields"]:
            if "null" in f:
                w(f"  static constexpr {cpp_type(f)} k{camel(f['name'])}Null = "
                  f"{cpp_literal(f['null'], f['type'])};")
        w("")
        for f in s["fields"]:
            if f["name"] == "msg_type" and "type_char" in s:
                init = f" = static_cast<std::uint8_t>('{s['type_char']}')"
            elif f["name"] == "version" and "type_char" in s:
                init = " = kVersion"
            elif "null" in f:
                init = f" = k{camel(f['name'])}Null"
            elif CHAR_RE.match(f["type"]):
                n = int(CHAR_RE.match(f["type"]).group(1))
                fill = f"'{f['pad']}'" if "pad" in f else "'\\0'"
                init = "{" + ", ".join([fill] * n) + "}"
            else:
                init = " = 0"
            w(f"  {cpp_type(f)} {f['name']}{init};  // @{f['offset']}: {f['doc']}")
        w("};")
        if not s.get("packed"):
            w(f"static_assert(sizeof({s['name']}) == {s['name']}::kWireSize);")
            for f in s["fields"]:
                w(f"static_assert(offsetof({s['name']}, {f['name']}) == {f['offset']});")
        w("")
        # write / read
        w(f"// Serializes to exactly {s['wire_size']} bytes.")
        w(f"inline void write(const {s['name']}& m, std::uint8_t* out) noexcept {{")
        for f in s["fields"]:
            w(f"  std::memcpy(out + {f['offset']}, &m.{f['name']}, {f['size']});")
        w("}")
        w(f"inline void read(const std::uint8_t* in, {s['name']}& m) noexcept {{")
        for f in s["fields"]:
            w(f"  std::memcpy(&m.{f['name']}, in + {f['offset']}, {f['size']});")
        w("}")
        w("")
    w("}  // namespace adsb::protocol")
    w("")
    return "\n".join(o)


