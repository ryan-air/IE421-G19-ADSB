def gen_py(schema: dict) -> str:
    o = []
    w = o.append
    w(f'"""{HEADER}')
    w("")
    w(schema["doc"])
    w("char[N] fields decode to str (latin-1) and encode from str or bytes.")
    w('"""')
    w("")
    w("import struct")
    w("")
    for c in schema["constants"]:
        w(f"{c['name']} = {c['value']}  # {c['doc']}")
    w("")
    for b in schema["bitsets"]:
        w(f"class {b['name']}:")
        w(f'    """{b["doc"]}"""')
        for bit in b["bits"]:
            w(f"    {bit['name']} = {1 << bit['bit']}  # {bit['doc']}")
        w("")
    w("")
    w("def _dec_chars(b):")
    w("    return b.decode('latin-1')")
    w("")
    w("")
    w("def _enc_chars(v, n, pad=b'\\x00'):")
    w("    b = v.encode('latin-1') if isinstance(v, str) else bytes(v)")
    w("    return b[:n].ljust(n, pad)")
    w("")
    for s in schema["structs"]:
        name = s["name"]
        sn = snake(name)
        fmt = struct_format(s)
        fields = [f["name"] for f in s["fields"]]
        chars = {f["name"]: int(CHAR_RE.match(f["type"]).group(1))
                 for f in s["fields"] if CHAR_RE.match(f["type"])}
        w("")
        w(f"# {s['doc']}")
        w(f"{sn.upper()}_FORMAT = {fmt!r}")
        w(f"{sn.upper()}_SIZE = {s['wire_size']}")
        w(f"{sn.upper()}_FIELDS = {tuple(fields)!r}")
        if "type_char" in s:
            w(f"{sn.upper()}_TYPE = {s['type_char']!r}")
        w(f"_{sn.upper()} = struct.Struct({sn.upper()}_FORMAT)")
        nulls = {f["name"]: f["null"] for f in s["fields"] if "null" in f}
        if nulls:
            w(f"{sn.upper()}_NULLS = {nulls!r}  # values meaning 'unknown'")
        w("")
        w("")
        w(f"def decode_{sn}(buf, offset=0):")
        w(f"    v = _{sn.upper()}.unpack_from(buf, offset)")
        w("    d = dict(zip(" + f"{sn.upper()}_FIELDS, v))")
        for cname in chars:
            w(f"    d[{cname!r}] = _dec_chars(d[{cname!r}])")
        w("    return d")
        w("")
        w("")
        w(f"def encode_{sn}(msg):")
        args = []
        for f in s["fields"]:
            if f["name"] in chars:
                pad = f.get("pad", "\0").encode("latin-1")
                args.append(f"_enc_chars(msg[{f['name']!r}], {chars[f['name']]}, {pad!r})")
            else:
                args.append(f"msg[{f['name']!r}]")
        w(f"    return _{sn.upper()}.pack(" + ", ".join(args) + ")")
        w("")
    typed = [s for s in schema["structs"] if "type_char" in s]
    w("")
    w("_DECODERS = {")
    for s in typed:
        w(f"    {s['type_char']!r}: ({s['name']!r}, decode_{snake(s['name'])}, {s['wire_size']}),")
    w("}")
    w("")
    w("")
    w("def decode_packet(buf):")
    w('    """Decodes one datagram -> (header, [(seq, type, name, msg_or_None)])."""')
    w("    if len(buf) < PACKET_HEADER_SIZE:")
    w("        raise ValueError('packet shorter than header')")
    w("    header = decode_packet_header(buf)")
    w("    out = []")
    w("    if header['count'] in (kEndOfSessionCount, kHeartbeatCount):")
    w("        if len(buf) != PACKET_HEADER_SIZE:")
    w("            raise ValueError('heartbeat / end-of-session packet has a body')")
    w("        return header, out")
    w("    off = PACKET_HEADER_SIZE")
    w("    for i in range(header['count']):")
    w("        if off + 2 > len(buf):")
    w("            raise ValueError('truncated message length')")
    w("        (length,) = struct.unpack_from('<H', buf, off)")
    w("        off += 2")
    w("        if off + length > len(buf):")
    w("            raise ValueError('truncated message body')")
    w("        t = chr(buf[off]) if length else ''")
    w("        d = _DECODERS.get(t)")
    w("        msg = d[1](buf, off) if d and length >= d[2] else None")
    w("        out.append((header['seq'] + i, t, d[0] if d else None, msg))")
    w("        off += length")
    w("    if off != len(buf):")
    w("        raise ValueError('trailing bytes after the last message')")
    w("    return header, out")
    w("")
    w("")
    w("def numpy_dtype(name):")
    w('    """NumPy structured dtype for a message, for bulk decoding of recordings."""')
    w("    import numpy as np")
    w("    layouts = {")
    for s in schema["structs"]:
        parts = []
        for f in s["fields"]:
            m = CHAR_RE.match(f["type"])
            parts.append((f["name"], f"S{m.group(1)}" if m else SCALARS[f["type"]][5]))
        w(f"        {s['name']!r}: {parts!r},")
    w("    }")
    w("    return np.dtype(layouts[name])")
    w("")
    return "\n".join(o)


